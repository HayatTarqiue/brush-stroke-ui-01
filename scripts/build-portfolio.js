#!/usr/bin/env node
/* Writes the portfolio cards from projects.js into index.html as static HTML,
   between the PORTFOLIO:START / PORTFOLIO:END markers, so search engines can
   read project names without executing JavaScript (SEO-9).
   Zero dependencies.   Usage:  node scripts/build-portfolio.js            */
'use strict';
const fs = require('fs');
const path = require('path');
const { projects, cardHTML } = require('../projects.js');

const file = path.join(__dirname, '..', 'index.html');
const html = fs.readFileSync(file, 'utf8');
const START = '<!-- PORTFOLIO:START (generated by scripts/build-portfolio.js — do not edit by hand) -->';
const END = '<!-- PORTFOLIO:END -->';
const a = html.indexOf(START), b = html.indexOf(END);
if (a === -1 || b === -1 || b < a) {
  console.error('Markers not found in index.html — expected PORTFOLIO:START / PORTFOLIO:END.');
  process.exit(1);
}
const cards = projects.map(cardHTML).join('');
const out = html.slice(0, a + START.length) + cards + '\n          ' + html.slice(b);
fs.writeFileSync(file, out);
console.log(`Wrote ${projects.length} portfolio cards into index.html`);
