#!/usr/bin/env node
/* Builds the portfolio from projects.js. Zero dependencies.
     node scripts/build-portfolio.js
   1. Writes the portfolio cards into index.html as static HTML (between the
      PORTFOLIO:START / PORTFOLIO:END markers) so search engines can read
      project names without running JavaScript (SEO-9).
   2. Writes a case-study page to projects/<slug>/index.html for every project
      that has a `story` in projects.js. Nav and footer are copied from
      index.html on each run, so they never drift from the home page.        */
'use strict';
const fs = require('fs');
const path = require('path');
const { PBASE, projects, catLabel, thumbOf, cardHTML, pageOf } = require('../projects.js');

/* ---------- production domain (SEO) ----------
   The production domain, no trailing slash (www and brush-sigma.vercel.app 301 here, see
   vercel.json). Rebuild after changing it. It turns on everything that needs absolute URLs:
   canonical + og:url on every page, absolute og:image / twitter:image, url/logo/image
   in the business JSON-LD, BreadcrumbList on project pages, sitemap.xml and the
   Sitemap line in robots.txt. Left empty, none of those are written: a canonical or
   sitemap pointing at the wrong host does more harm than having none. */
const SITE_URL = (process.env.SITE_URL || 'https://brushstrokeartspace.com').replace(/\/+$/, '');

const ROOT = path.join(__dirname, '..');
const indexFile = path.join(ROOT, 'index.html');
let html = fs.readFileSync(indexFile, 'utf8');

/* ---------- 1. static cards in index.html ---------- */
const START = '<!-- PORTFOLIO:START (generated by scripts/build-portfolio.js — do not edit by hand) -->';
const END = '<!-- PORTFOLIO:END -->';
const a = html.indexOf(START), b = html.indexOf(END);
if (a === -1 || b === -1 || b < a) {
  console.error('Markers not found in index.html — expected PORTFOLIO:START / PORTFOLIO:END.');
  process.exit(1);
}
html = html.slice(0, a + START.length) + projects.map(cardHTML).join('') + '\n          ' + html.slice(b);

/* ---------- cache-busting: content hash on every local CSS/JS reference ----------
   The files aren't fingerprinted, so a browser (or a dev server with no cache headers)
   could keep running an old script.js after a change. `script.js?v=<hash>` changes
   whenever the file's content changes, and only then. */
const crypto = require('crypto');
const ASSETS = ['styles.css', 'project.css', 'theme-light.css', 'pricing.js', 'projects.js', 'script.js'];
const ver = Object.fromEntries(ASSETS.map(f => [f,
  crypto.createHash('sha1').update(fs.readFileSync(path.join(ROOT, f))).digest('hex').slice(0, 8)]));
const stamp = doc => doc.replace(/(href|src)="(styles\.css|project\.css|theme-light\.css|pricing\.js|projects\.js|script\.js)(\?v=[0-9a-f]+)?"/g,
  (m, attr, file) => `${attr}="${file}?v=${ver[file]}"`);
html = stamp(html);

/* ---------- absolute URLs on the home page (only when SITE_URL is set) ----------
   Everything lives between SEO:START / SEO:END markers plus the JSON-LD, so a rebuild
   with a different (or empty) SITE_URL rewrites it cleanly. */
const abs = rel => SITE_URL + '/' + String(rel).replace(/^\/+/, '');
{
  const S = '<!-- SEO:START (generated by scripts/build-portfolio.js from SITE_URL) -->', E = '<!-- SEO:END -->';
  const i = html.indexOf(S), j = html.indexOf(E);
  if (i === -1 || j === -1) { console.error('SEO:START / SEO:END markers not found in index.html'); process.exit(1); }
  const block = SITE_URL ? `
  <link rel="canonical" href="${abs('')}" />
  <meta property="og:url" content="${abs('')}" />
  <meta property="og:image" content="${abs('assets/og-image.jpg')}" />
  <meta name="twitter:image" content="${abs('assets/og-image.jpg')}" />
  ` : `
  <!-- no domain yet: relative og:image (WhatsApp/LinkedIn previews need it absolute) -->
  <meta property="og:image" content="assets/og-image.jpg" />
  `;
  html = html.slice(0, i + S.length) + block + html.slice(j);

  // business JSON-LD: add url / logo / image and a WebSite node (gives Google the site name)
  html = html.replace(/(<script type="application\/ld\+json">)([\s\S]*?)(<\/script>)/, (m, open, json, close) => {
    let ld = JSON.parse(json);
    const biz = ld['@graph'] ? ld['@graph'].find(n => n['@type'] !== 'WebSite') : ld;
    delete biz['@context'];
    for (const k of ['@id', 'url', 'logo', 'image']) delete biz[k];
    if (!SITE_URL) return `${open}\n  ${JSON.stringify({ '@context': 'https://schema.org', ...biz }, null, 2).replace(/\n/g, '\n  ')}\n  ${close}`;
    const out = {
      '@context': 'https://schema.org',
      '@graph': [
        { '@id': abs('#business'), ...biz, url: abs(''), logo: abs('assets/icon-512.png'), image: abs('assets/og-image.jpg') },
        { '@type': 'WebSite', '@id': abs('#website'), url: abs(''), name: 'Brush Stroke', alternateName: biz.name,
          inLanguage: 'en-IN', publisher: { '@id': abs('#business') } },
      ],
    };
    return `${open}\n  ${JSON.stringify(out, null, 2).replace(/\n/g, '\n  ')}\n  ${close}`;
  });
}
fs.writeFileSync(indexFile, html);
console.log(`Wrote ${projects.length} portfolio cards into index.html`);

/* ---------- 2. case-study pages ---------- */
const esc = s => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const grab = (re, what) => {
  const m = html.match(re);
  if (!m) { console.error(`Could not find the ${what} in index.html`); process.exit(1); }
  return m[0];
};
const nav = grab(/<header class="nav" id="nav">[\s\S]*?<\/header>/, 'nav')
  // on a project page "Portfolio" is the current section, not "Home"
  .replace('class="nav__link is-active"', 'class="nav__link"')
  .replace('<a href="#portfolio" class="nav__link">', '<a href="#portfolio" class="nav__link is-active" aria-current="page">');
const footer = grab(/<footer class="footer">[\s\S]*?<\/footer>/, 'footer');
const progress = grab(/<div class="scroll-progress"[^>]*><\/div>/, 'scroll progress bar');
const toTop = grab(/<button class="to-top"[\s\S]*?<\/button>/, 'back-to-top button');
const fonts = grab(/<link href="https:\/\/fonts\.googleapis\.com\/css2[^>]*>/, 'font link');
// ~1 KB blurred hero previews written by scripts/make-mobile-heroes.py
const lqipFile = path.join(ROOT, 'scripts', 'hero-lqip.json');
const LQIP_HERO = fs.existsSync(lqipFile) ? JSON.parse(fs.readFileSync(lqipFile, 'utf8')) : {};
const themeLoader = grab(/<script>if\(\/\[\?&\]theme=light[\s\S]*?<\/script>/, 'theme preview loader');

function pageHTML(p, pi) {
  const s = p.story;
  const loc = p.loc;
  // "Mocha — Café & Lounge Interior Design, Pune | Brush Stroke": what people search for
  // (venue type + city) first; the brand suffix is dropped when it would push past ~65 chars
  const venueFact = (s.facts.find(([k]) => k === 'Venue') || [])[1];
  const venue = venueFact ? venueFact.replace(/(^|\s)(\p{L})/gu, (m, sp, c) => sp + c.toUpperCase()) : catLabel[p.cat];
  const base = `${s.name} — ${venue} Interior Design, ${loc}`;
  const title = base.length + 15 <= 65 ? `${base} | Brush Stroke` : base;
  const url = SITE_URL ? abs(pageOf(p)) : '';
  // `cover` picks the hero photograph (a landscape frame reads best full-width); defaults to the first
  const coverIdx = Number.isInteger(s.cover) && p.imgs[s.cover] ? s.cover : 0;
  const cover = PBASE + p.imgs[coverIdx];
  // phones: the full-height centre crop made by scripts/make-mobile-heroes.py (falls back to the thumbnail)
  const cropM = `assets/hero/pp-${p.slug}-m.jpg`;
  const coverM = fs.existsSync(path.join(ROOT, cropM)) ? cropM : PBASE + thumbOf(p.imgs[coverIdx]);
  if (!LQIP_HERO[p.slug]) console.warn(`  ! no blurred hero preview for ${p.slug} — run scripts/make-mobile-heroes.py`);
  if (!fs.existsSync(path.join(ROOT, cropM))) console.warn(`  ! ${cropM} missing — run scripts/make-mobile-heroes.py (using the thumbnail meanwhile)`);
  const work = {
    '@type': 'CreativeWork',
    name: `${s.name} — ${venue.toLowerCase()} interior design, ${loc}`, description: s.intro,
    inLanguage: 'en-IN',
    locationCreated: { '@type': 'Place', name: loc },
    creator: SITE_URL ? { '@id': abs('#business') } : { '@type': 'Organization', name: 'Brush Stroke Artspace' },
    image: p.imgs.map(rel => SITE_URL ? abs(PBASE + rel) : PBASE + rel),
  };
  // BreadcrumbList needs absolute item URLs, so it only exists once the domain is known
  const ld = !SITE_URL ? { '@context': 'https://schema.org', ...work } : {
    '@context': 'https://schema.org',
    '@graph': [
      { ...work, '@id': url + '#work', url, mainEntityOfPage: url },
      { '@type': 'BreadcrumbList', itemListElement: [
        { '@type': 'ListItem', position: 1, name: 'Home', item: abs('') },
        { '@type': 'ListItem', position: 2, name: 'Projects', item: abs('#portfolio') },
        { '@type': 'ListItem', position: 3, name: s.name, item: url },
      ] },
    ],
  };
  const facts = s.facts.map(([k, v], i) => `<div class="reveal" data-reveal data-delay="${i * 90}"><dt>${esc(k)}</dt><dd>${esc(v)}</dd></div>`).join('\n          ');
  const spaces = s.spaces.map(sp => `
        <article class="pp-space reveal" data-reveal>
          <button class="pp-space__img" type="button" data-lb-project="${pi}" data-lb-index="${sp.img}"
            aria-label="Open photo: ${esc(sp.title)}">
            <!-- data-src: released by script.js once the hero photo has loaded, so on a slow
                 connection these never compete with it (noscript keeps them for no-JS) -->
            <img data-src="${PBASE}${thumbOf(p.imgs[sp.img])}" alt="${esc(s.name)}, ${esc(loc)} — ${esc(sp.title.toLowerCase())}" loading="lazy" decoding="async" />
            <noscript><img src="${PBASE}${thumbOf(p.imgs[sp.img])}" alt="${esc(s.name)}, ${esc(loc)} — ${esc(sp.title.toLowerCase())}" /></noscript>
          </button>
          <div class="pp-space__text">
            <h3>${esc(sp.title)}</h3>
            <p>${esc(sp.text)}</p>
          </div>
        </article>`).join('');
  // closing panel uses the last space's photo (a different mood from the hero)
  // ...but never the hero photo again
  const ctaPick = [...s.spaces].reverse().map(sp => sp.img).find(i => i !== coverIdx);
  const ctaImg = ctaPick != null ? ctaPick : (coverIdx === p.imgs.length - 1 ? 0 : p.imgs.length - 1);
  // next project that also has a story (wraps around); falls back to the portfolio
  const others = projects.filter(q => q.story && q !== p);
  const next = others.length ? (others.find(q => projects.indexOf(q) > pi) || others[0]) : null;   // wraps after the last

  return `<!DOCTYPE html>
<!-- GENERATED by scripts/build-portfolio.js from projects.js — edit those, not this file. -->
<html lang="en-IN">
<head>
  <meta charset="UTF-8" />
  <script>document.documentElement.classList.add('js');</script>
  <!-- Back/Forward gets a plain crossfade instead of the forward fade-and-rise. Must run
       before first render: the cross-page transition is revealed on this (new) page. -->
  <script>addEventListener('pagereveal',function(e){var a=window.navigation&&navigation.activation;if(e.viewTransition&&a&&a.navigationType==='traverse')e.viewTransition.types.add('back')});</script>
  <meta name="viewport" content="width=device-width, initial-scale=1.0" />
  <meta name="theme-color" content="#0B1E2E" />
  <!-- every relative URL on this page resolves from the site root -->
  <base href="/" />
  <title>${esc(title)}</title>
  <meta name="description" content="${esc(s.intro)}" />
${s.published ? `  <meta name="robots" content="index, follow, max-image-preview:large" />
` : `  <!-- Draft copy: kept out of Google until the studio approves it
       (set \`published: true\` for this project in projects.js, then rebuild). -->
  <meta name="robots" content="noindex, follow" />
`}  <meta property="og:title" content="${esc(s.name)} — Interiors by Brush Stroke" />
  <meta property="og:description" content="${esc(s.intro)}" />
  <meta property="og:type" content="article" />
  <meta property="og:site_name" content="Brush Stroke" />
  <meta property="og:locale" content="en_IN" />
${SITE_URL ? `  <link rel="canonical" href="${url}" />
  <meta property="og:url" content="${url}" />
  <meta property="og:image" content="${abs(cover)}" />
  <meta name="twitter:image" content="${abs(cover)}" />
` : `  <!-- set SITE_URL in scripts/build-portfolio.js for canonical, og:url and an absolute og:image -->
  <meta property="og:image" content="${cover}" />
`}  <meta property="og:image:alt" content="${esc(s.name)}, ${esc(loc)} — interior by Brush Stroke" />
  <meta name="twitter:card" content="summary_large_image" />
  <link rel="icon" type="image/png" href="assets/favicon-64.png" />
  <!-- Prerender a project page as soon as the visitor shows intent (hover on desktop, touch on
       phones): HTML, CSS and hero photo are ready, so the page fade starts at once. At most two
       pages are kept warm. Ignored by browsers without Speculation Rules. -->
  <script type="speculationrules">{"prerender":[{"where":{"href_matches":"/projects/*"},"eagerness":"moderate"}]}</script>
  <link rel="apple-touch-icon" href="assets/apple-touch-icon.png" />
  <link rel="preload" as="image" href="${coverM}" media="(max-width: 760px)" fetchpriority="high" />
  <link rel="preload" as="image" href="${cover}" media="(min-width: 761px)" fetchpriority="high" />
  <link rel="preconnect" href="https://fonts.googleapis.com" />
  <link rel="preconnect" href="https://fonts.gstatic.com" crossorigin />
  ${fonts}
  <link rel="stylesheet" href="styles.css" />
  <link rel="stylesheet" href="project.css" />
  ${themeLoader}
  <script type="application/ld+json">${JSON.stringify(ld)}</script>
</head>
<body class="pp">
  ${progress}

  ${nav}

  <main>
    <section class="pp-hero">
      ${LQIP_HERO[p.slug] ? `<span class="pp-hero__lqip" aria-hidden="true" style="background-image:url('${LQIP_HERO[p.slug]}')"></span>` : ''}
      <picture>
        <source media="(max-width: 760px)" srcset="${coverM}" />
        <img class="pp-hero__img" src="${cover}" alt="${esc(s.name)}, ${esc(loc)} — ${esc(venue.toLowerCase())} interior design by Brush Stroke" fetchpriority="high" />
      </picture>
      <div class="container pp-hero__inner">
        <a class="pp-back reveal" data-reveal href="#portfolio"><svg viewBox="0 0 24 24" width="16" height="16" aria-hidden="true"><path d="M19 12H5M11 6l-6 6 6 6" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round"/></svg>All projects</a>
        <p class="pp-eyebrow reveal" data-reveal data-delay="80">${esc(catLabel[p.cat])} <span aria-hidden="true">·</span> ${esc(loc)}</p>
        <h1 class="reveal" data-reveal data-delay="160"><span class="pp-hero__title">${esc(s.name)}</span></h1>
        <p class="pp-hero__lead reveal" data-reveal data-delay="320">${esc(s.intro)}</p>
      </div>
    </section>

    <section class="pp-facts" aria-label="Project facts">
      <div class="container">
        <dl>
          ${facts}
        </dl>
      </div>
    </section>

    <section class="pp-section pp-overview" aria-label="About the project">
      <div class="container">
        <span class="kicker reveal" data-reveal>The project</span>
        <h2 class="pp-statement reveal" data-reveal data-delay="80">${esc(s.statement)}</h2>
        <div class="pp-overview__body reveal" data-reveal data-delay="180">
          ${s.overview.map(t => `<p>${esc(t)}</p>`).join('\n          ')}
        </div>
      </div>
    </section>

    <section class="pp-section pp-section--alt pp-spaces" aria-label="Spaces">
      <div class="container">
        <header class="sec-head reveal" data-reveal>
          <span class="kicker">Inside ${esc(p.t)}</span>
          <h2 class="sec-title">Space by <em>space</em></h2>
        </header>
        <div class="pp-spaces__list">${spaces}
        </div>
        <div class="pp-spaces__more reveal" data-reveal>
          <button class="btn btn--ghost" type="button" data-lb-all="${pi}"><span>View all ${p.imgs.length} photos</span>
            <svg viewBox="0 0 24 24" class="btn__ico" aria-hidden="true"><path d="M4 7h14v11H4zM7 4h14v11" fill="none" stroke="currentColor" stroke-width="1.8" stroke-linejoin="round"/></svg></button>
        </div>
      </div>
    </section>

    <section class="pp-section pp-materials" aria-label="Materials and details">
      <div class="container pp-materials__wrap">
        <header class="sec-head sec-head--left reveal" data-reveal>
          <span class="kicker">Materials &amp; details</span>
          <h2 class="sec-title">What it's <em>made of</em></h2>
        </header>
        <ul class="pp-materials__list">
          ${s.materials.map((m, i) => `<li class="reveal" data-reveal data-delay="${(i % 3) * 70}">${esc(m)}</li>`).join('\n          ')}
        </ul>
      </div>
    </section>

    <section class="pp-section pp-cta" aria-label="Start a project">
      <div class="container">
        <div class="pp-cta__panel reveal" data-reveal>
          <picture>
            <source media="(max-width: 760px)" srcset="${PBASE}${thumbOf(p.imgs[ctaImg])}" />
            <img class="pp-cta__img" src="${PBASE}${p.imgs[ctaImg]}" alt="" loading="lazy" decoding="async" />
          </picture>
          <div class="pp-cta__content">
            <span class="kicker">Your space next</span>
            <h2>Planning a café, bar<br/>or restaurant?</h2>
            <p>Tell us about your space and we'll come back with ideas, a plan and an estimate.</p>
            <div class="pp-cta__actions">
              <a href="#contact" class="btn btn--primary"><span>Get a Free Consultation</span>
                <svg viewBox="0 0 24 24" class="btn__ico" aria-hidden="true"><path d="M5 12h14M13 6l6 6-6 6" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round"/></svg></a>
              ${next ? `<a href="${pageOf(next)}" class="btn btn--ghost"><span>Next project: ${esc(next.t)}</span></a>`
                     : `<a href="#portfolio" class="btn btn--ghost"><span>See All Projects</span></a>`}
            </div>
          </div>
        </div>
      </div>
    </section>
  </main>

  ${footer}

  ${toTop}

  <script src="pricing.js" defer></script>
  <script src="projects.js" defer></script>
  <script src="script.js" defer></script>
</body>
</html>
`;
}

let pages = 0;
projects.forEach((p, pi) => {
  if (!pageOf(p)) return;
  const dir = path.join(ROOT, pageOf(p));
  fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(path.join(dir, 'index.html'), stamp(pageHTML(p, pi)));
  pages++;
  console.log(`Wrote ${pageOf(p)}index.html${p.story.published ? '' : '  (noindex — awaiting studio approval)'}`);
});
if (!pages) console.log('No projects have a story yet — no case-study pages written.');

/* ---------- 3. sitemap.xml + robots.txt ----------
   Only indexable pages go in the sitemap: the home page, plus project pages whose story is
   `published` (a noindex page listed in a sitemap is a mixed signal Search Console flags). */
const robotsFile = path.join(ROOT, 'robots.txt'), sitemapFile = path.join(ROOT, 'sitemap.xml');
if (SITE_URL) {
  const imgTags = imgs => imgs.map(rel => `\n    <image:image><image:loc>${esc(abs(rel))}</image:loc></image:image>`).join('');
  // home: the share image plus every portfolio card photo it shows
  const entries = [`  <url>\n    <loc>${abs('')}</loc>${imgTags(['assets/og-image.jpg', ...projects.map(p => PBASE + thumbOf(p.imgs[0]))])}\n  </url>`]
    .concat(projects.filter(p => p.story && p.story.published).map(p =>
      `  <url>\n    <loc>${abs(pageOf(p))}</loc>${imgTags(p.imgs.map(rel => PBASE + rel))}\n  </url>`));
  fs.writeFileSync(sitemapFile, `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:image="http://www.google.com/schemas/sitemap-image/1.1">
${entries.join('\n')}
</urlset>
`);
  console.log(`Wrote sitemap.xml (${entries.length} URL${entries.length > 1 ? 's' : ''})`);
} else if (fs.existsSync(sitemapFile)) {
  fs.unlinkSync(sitemapFile);
}
fs.writeFileSync(robotsFile, `User-agent: *
Allow: /
${SITE_URL ? `\nSitemap: ${abs('sitemap.xml')}\n` : `
# The Sitemap line is written by scripts/build-portfolio.js once SITE_URL is set.
`}`);
if (!SITE_URL) console.log('SITE_URL is empty: no canonical URLs, absolute OG images or sitemap.xml (set it in scripts/build-portfolio.js)');
